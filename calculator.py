"""
Простой калькулятор на Python.
Демонстрирует функции, аргументы, возврат значений.
"""

def add(a, b):
    """Сложение двух чисел."""
    return a + b

def subtract(a, b):
    """Вычитание двух чисел."""
    return a - b

if __name__ == "__main__":
    print(add(5, 3))        # 8
    print(subtract(10, 4))  # 6
